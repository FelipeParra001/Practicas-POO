package Modelo;

/**
 * Representa un gasto en implemento tecnológico.
 */
public class ImplementoTecnologico {
    // Atributos
    private double monto;

    // Constructor
    public ImplementoTecnologico(double monto) {
        this.monto = monto;
    }

    // Getters y Setters
    public double getMonto() {
        return monto;
    }

    public void setMonto(double monto) {
        this.monto = monto;
    }
}
